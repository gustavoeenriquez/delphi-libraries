#!/usr/bin/env python3
"""Genera src/OpusCeltEncTables.pas a partir de celt/static_modes_float.h de libopus.

Uso:  python gen_celt_enc_tables.py <ruta a static_modes_float.h> <salida .pas>

Copia literal (mismos literales float) de las tablas del modo 48 kHz / 960 que
usa la MDCT directa del encoder: twiddles de la FFT, tablas bitrev y trig de
la MDCT. Así la FFT del port usa exactamente los mismos coeficientes que
libopus (los literales de 8 cifras no siempre coinciden con recalcularlos).
"""
import re
import sys


def grab(src, name):
    m = re.search(r'static const [^\n]*\b' + re.escape(name) + r'\[\d+\]\s*=\s*\{(.*?)\};', src, re.S)
    if not m:
        sys.exit('no encuentro ' + name)
    return m.group(1)


def floats(body):
    vals = re.findall(r'[-+]?\d+\.\d*(?:[eE][-+]?\d+)?f?|[-+]?\d+(?:[eE][-+]?\d+)?f', body)
    return [v.rstrip('f') for v in vals]


def ints(body):
    return re.findall(r'-?\d+', body)


def fmt(vals, per_line, indent='    '):
    lines = []
    for i in range(0, len(vals), per_line):
        lines.append(indent + ', '.join(vals[i:i + per_line]))
    return ',\n'.join(lines)


def main():
    src = open(sys.argv[1], encoding='utf-8').read()
    out = []
    out.append('unit OpusCeltEncTables;')
    out.append('')
    out.append('{')
    out.append('  OpusCeltEncTables.pas - Forward MDCT / FFT tables of the CELT 48 kHz / 960 mode')
    out.append('')
    out.append('  GENERATED by tools/gen_celt_enc_tables.py from celt/static_modes_float.h of')
    out.append('  libopus 1.5.2 (same float literals). Do not edit. Table data Copyright (c)')
    out.append('  2007-2009 Xiph.Org Foundation, used under the libopus BSD license.')
    out.append('}')
    out.append('')
    out.append('interface')
    out.append('')
    out.append('type')
    out.append('  TKissCpx = record')
    out.append('    R, I: Single;')
    out.append('  end;')
    out.append('')
    out.append('const')
    tw = floats(grab(src, 'fft_twiddles48000_960'))
    assert len(tw) == 960, len(tw)
    pairs = ['(R: %s; I: %s)' % (tw[2 * k], tw[2 * k + 1]) for k in range(480)]
    out.append('  FFT_TWIDDLES480: array[0..479] of TKissCpx = (')
    out.append(fmt(pairs, 2) + ');')
    out.append('')
    for n in (480, 240, 120, 60):
        b = ints(grab(src, 'fft_bitrev%d' % n))
        assert len(b) == n, (n, len(b))
        out.append('  FFT_BITREV%d: array[0..%d] of SmallInt = (' % (n, n - 1))
        out.append(fmt(b, 16) + ');')
        out.append('')
    tr = floats(grab(src, 'mdct_twiddles960'))
    assert len(tr) == 1800, len(tr)
    out.append('  MDCT_TRIG960: array[0..1799] of Single = (')
    out.append(fmt(tr, 6) + ');')
    out.append('')
    # factores de cada sub-FFT (480, 240, 120, 60)
    facs = re.findall(r'\{(\d+(?:,\s*\d+)*),\s*\},\s*/\* factors \*/', src)
    assert len(facs) == 4, facs
    out.append('  FFT_FACTORS: array[0..3, 0..15] of SmallInt = (')
    rows = []
    for f in facs:
        v = [x.strip() for x in f.split(',')]
        v += ['0'] * (16 - len(v))
        rows.append('    (' + ', '.join(v) + ')')
    out.append(',\n'.join(rows) + ');')
    out.append('')
    out.append('implementation')
    out.append('')
    out.append('end.')
    with open(sys.argv[2], 'w', encoding='ascii', newline='\r\n') as f:
        f.write('\n'.join(out) + '\n')


if __name__ == '__main__':
    main()
