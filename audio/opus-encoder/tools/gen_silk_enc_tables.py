#!/usr/bin/env python3
"""Genera src/OpusSilkEncTables.pas a partir de las tablas de silk/ de libopus.

Uso:  python gen_silk_enc_tables.py <directorio silk/ de libopus 1.5.2> <salida .pas>

Copia literal de los arrays constantes (tables_*.c, table_LSF_cos.c,
pitch_est_tables.c, resampler_rom.c). Los nombres pasan a mayúsculas con
prefijo SE_ (silk encoder) para no chocar con las tablas del decoder.
Los #define que aparecen en dimensiones o valores se sustituyen; el script
aborta si queda algún identificador sin resolver. Las tablas de punteros y las
estructuras (codebooks NLSF) se arman a mano en OpusSilkEncTables.
"""
import os
import re
import sys

FILES = ['tables_gain.c', 'tables_LTP.c', 'tables_NLSF_CB_NB_MB.c', 'tables_NLSF_CB_WB.c',
         'tables_other.c', 'tables_pitch_lag.c', 'tables_pulses_per_block.c',
         'table_LSF_cos.c', 'pitch_est_tables.c', 'resampler_rom.c']
HEADERS = ['define.h', 'pitch_est_defines.h', 'resampler_rom.h', 'resampler_private.h']
TYPES = {'opus_uint8': 'Byte', 'unsigned char': 'Byte', 'opus_int8': 'ShortInt',
         'opus_int16': 'SmallInt', 'opus_int32': 'Integer', 'opus_uint16': 'Word'}


def strip_comments(s):
    s = re.sub(r'/\*.*?\*/', ' ', s, flags=re.S)
    return re.sub(r'//[^\n]*', ' ', s)


def load_defines(silk):
    defs = {}
    for h in HEADERS:
        p = os.path.join(silk, h)
        if not os.path.exists(p):
            continue
        for line in strip_comments(open(p, encoding='latin-1').read()).splitlines():
            m = re.match(r'\s*#\s*define\s+(\w+)\s+(.+?)\s*$', line)
            if m:
                defs[m.group(1)] = m.group(2)
    return defs


def expand(expr, defs, depth=0):
    if depth > 20:
        sys.exit('recursión de macros en ' + expr)
    def rep(m):
        w = m.group(0)
        if w in defs:
            return '(' + expand(defs[w], defs, depth + 1) + ')'
        return w
    return re.sub(r'\b[A-Za-z_]\w*\b', rep, expr)


def ev(expr, defs):
    e = expand(expr, defs)
    e = re.sub(r'(\d)[fF]\b', r'\1', e)
    e = e.replace('/', '//')
    if re.search(r'[A-Za-z_]', e):
        sys.exit('identificador sin resolver: ' + expr + ' -> ' + e)
    return int(eval(e))


def main():
    silk, out = sys.argv[1], sys.argv[2]
    defs = load_defines(silk)
    lines = ['unit OpusSilkEncTables;', '', '{',
             '  OpusSilkEncTables.pas - SILK tables used by the encoder',
             '',
             '  GENERATED by tools/gen_silk_enc_tables.py from silk/*.c of libopus 1.5.2.',
             '  Do not edit. Table data Copyright (c) 2006-2011 Skype Limited, used under',
             '  the libopus BSD license.', '}', '', 'interface', '', 'const']
    seen = set()
    for fn in FILES:
        src = strip_comments(open(os.path.join(silk, fn), encoding='latin-1').read())
        for m in re.finditer(r'(?:static\s+)?const\s+(opus_uint8|opus_int8|opus_int16|opus_int32|opus_uint16|unsigned char)'
                             r'\s+(\w+)\s*((?:\[[^\]]*\]\s*)+)=\s*\{(.*?)\}\s*;', src, re.S):
            ctype, name, dims_s, body = m.groups()
            if name in seen:
                continue
            seen.add(name)
            dims = [ev(d, defs) for d in re.findall(r'\[([^\]]*)\]', dims_s)]
            vals = [v.strip() for v in re.split(r'[,{}\s]+', body) if v.strip()]
            vals = [str(ev(v, defs)) for v in vals]
            total = 1
            for d in dims:
                total *= d
            if len(vals) != total:
                sys.exit('%s: %d valores, se esperaban %d' % (name, len(vals), total))
            pname = 'SE_' + name[5:].upper() if name.startswith('silk_') else 'SE_' + name.upper()
            ptype = TYPES[ctype]
            rng = ', '.join('0..%d' % (d - 1) for d in dims)

            def nest(level, offset):
                if level == len(dims) - 1:
                    chunk = vals[offset:offset + dims[level]]
                    rows = [', '.join(chunk[i:i + 16]) for i in range(0, len(chunk), 16)]
                    ind = '    ' + '  ' * level
                    return '(' + (',\n' + ind).join(rows) + ')'
                size = 1
                for d in dims[level + 1:]:
                    size *= d
                parts = [nest(level + 1, offset + i * size) for i in range(dims[level])]
                ind = '    ' + '  ' * level
                return '(\n' + ind + ('  ' if False else '') + (',\n' + ind).join(parts) + ')'
            lines.append('  %s: array[%s] of %s = %s;' % (pname, rng, ptype, nest(0, 0)))
            lines.append('')
    # numeric defines that the Pascal code needs
    lines.append('implementation')
    lines.append('')
    lines.append('end.')
    with open(out, 'w', encoding='ascii', newline='\r\n') as f:
        f.write('\n'.join(lines) + '\n')
    print('tablas:', len(seen))


if __name__ == '__main__':
    main()
