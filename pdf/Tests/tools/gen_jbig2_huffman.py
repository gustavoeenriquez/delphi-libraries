"""Generates the standard Huffman tables B.1-B.15 of ITU-T T.88 for
uPDF.JBIG2.pas from the text of the Recommendation (the DOCX of the
T.88 (08/2018) package converted to plain text, one paragraph per line).

Each table line becomes (PREFLEN, RANGELEN, RANGELOW, kind) in the order of
B.2 (normal lines, lower range, upper range, out-of-band); the prefix codes
are then assigned with the algorithm of B.3 and checked against the
encodings printed in B.5.

Usage: python gen_jbig2_huffman.py t88.txt > tables.inc
"""
import re, sys

text = open(sys.argv[1], encoding='utf-8').read().split('\n')
# the last occurrence: the first one is the table of contents
start = max(i for i, l in enumerate(text) if l.startswith('B.5\tStandard Huffman tables'))
NORMAL, LOWER, UPPER, OOB = 0, 1, 2, 3


def num(s):
    return int(s.replace('–', '-').replace(' ', ''))


def assign(preflens):
    # B.3
    lenmax = max(preflens)
    count = [0] * (lenmax + 1)
    for p in preflens:
        count[p] += 1
    count[0] = 0
    first = [0] * (lenmax + 1)
    codes = [None] * len(preflens)
    for curlen in range(1, lenmax + 1):
        first[curlen] = (first[curlen - 1] + count[curlen - 1]) * 2
        code = first[curlen]
        for i, p in enumerate(preflens):
            if p == curlen:
                codes[i] = format(code, '0%db' % p)
                code += 1
    return codes


tables = []
i = start
while len(tables) < 15:
    m = re.match(r'Table\sB\.(\d+)\s+\S\s+Standard Huffman table', text[i])
    if not m:
        i += 1
        continue
    n = int(m.group(1))
    i += 1
    assert text[i].strip() == 'HTOOB'
    htoob = int(text[i + 1])
    i += 2
    while text[i].strip() != 'Encoding':
        i += 1
    i += 1
    # the non-empty lines up to the next table or clause
    cells = []
    while i < len(text) and not re.match(r'Table\sB\.', text[i]) and not re.match(r'^[A-Z]\.\d', text[i]) \
            and not text[i].startswith('Annex'):
        # the infinity sign is a Symbol font character (U+F0A5)
        cell = text[i].replace('', '').replace('∞', '').strip()
        if cell:
            cells.append(cell)
        i += 1
    rows = []
    k = 0
    while k < len(cells):
        val = cells[k]
        if val == 'OOB':
            rows.append((OOB, int(cells[k + 1]), 0, 0, cells[k + 2].split()[0]))
            k += 3
            continue
        if not re.match(r'^[–\-0-9]', val):
            break
        pref, rlen, enc = int(cells[k + 1]), int(cells[k + 2]), cells[k + 3].split()[0]
        k += 4
        if val.startswith('– . . .') or val.startswith('- . . .'):
            rows.append((LOWER, pref, rlen, num(val.split('. . .')[1]), enc))
        elif val.endswith('. . .'):
            rows.append((UPPER, pref, rlen, num(val.split('. . .')[0]), enc))
        elif '. . .' in val:
            rows.append((NORMAL, pref, rlen, num(val.split('. . .')[0]), enc))
        else:
            rows.append((NORMAL, pref, rlen, num(val), enc))
    ordered = [r for r in rows if r[0] == NORMAL] + [r for r in rows if r[0] == LOWER] + \
              [r for r in rows if r[0] == UPPER] + [r for r in rows if r[0] == OOB]
    codes = assign([r[1] for r in ordered])
    for r, c in zip(ordered, codes):
        assert c == r[4], 'Table B.%d: %s assigned %s, printed %s' % (n, r, c, r[4])
    assert bool(htoob) == any(r[0] == OOB for r in ordered)
    tables.append((n, ordered))

kinds = ['hlNormal', 'hlLower', 'hlUpper', 'hlOOB']
total = sum(len(t[1]) for t in tables)
print('  // Standard Huffman tables B.1-B.15 (generated by Tests/tools/gen_jbig2_huffman.py):')
print('  // PREFLEN, RANGELEN, RANGELOW, kind; lines in the order of B.2')
print('  STD_LINES: array[0..%d] of THuffLine = (' % (total - 1))
out = []
for n, rows in tables:
    for k, r in enumerate(rows):
        out.append('    (PrefLen: %2d; RangeLen: %2d; RangeLow: %7d; Kind: %s)%s' % (
            r[1], r[2], r[3], kinds[r[0]], '   // B.%d' % n if k == 0 else ''))
for j, l in enumerate(out):
    if j < len(out) - 1:
        l = l.replace(')', '),', 1) if '//' not in l else l.replace(')   //', '),   //')
    else:
        l = l.replace(')', '));', 1) if '//' not in l else l.replace(')   //', '));   //')
    print(l)
first = 0
starts = []
for n, rows in tables:
    starts.append(first)
    first += len(rows)
starts.append(first)
print('  STD_START: array[1..16] of Integer = (%s);' % ', '.join(map(str, starts)))
