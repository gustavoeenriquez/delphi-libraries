w('  LATIN_GLYPHS: array[0..%d] of string = (\n' % (len(latin) - 1))
w('\n'.join(rows([pstr(g) for g in latin], 6)) + ');\n\n')
w('  // Widths of LATIN_GLYPHS in the fonts 0..11\n')
w('  LATIN_WIDTHS: array[0..11, 0..%d] of SmallInt = (\n' % (len(latin) - 1))
blocks = []
for n in FONTS[:12]:
    blocks.append('    ( // %s\n' % n + '\n'.join(rows([str(afm[n][0][g]) for g in latin], 16, '      ')) + ')')
w(',\n'.join(blocks) + ');\n\n')
for title, glyphs, fname in (('SYMBOL', symbol, 'Symbol'), ('DINGBATS', dingbats, 'ZapfDingbats')):
    w('  %s_GLYPHS: array[0..%d] of string = (\n' % (title, len(glyphs) - 1))
    w('\n'.join(rows([pstr(g) for g in glyphs], 6)) + ');\n')
    w('  %s_WIDTHS: array[0..%d] of SmallInt = (\n' % (title, len(glyphs) - 1))
    w('\n'.join(rows([str(afm[fname][0][g]) for g in glyphs], 16)) + ');\n\n')
for title, enc in (('ENC_STANDARD', standard), ('ENC_WINANSI', win), ('ENC_MACROMAN', mac),
                   ('ENC_SYMBOL', sym), ('ENC_DINGBATS', zd)):
    w('  %s: array[0..255] of string = (\n' % title)
    w('\n'.join(rows([pstr(g) for g in enc], 8)) + ');\n\n')
names = sorted(uni)
w('  AGL: array[0..%d] of TAGLEntry = (\n' % (len(names) - 1))
w('\n'.join(rows(['(N: %s; U: %s)' % (pstr(n), pchars(uni[n])) for n in names], 3)) + ');\n')
w('''
var
  GLatin, GSymbol, GDingbats: TDictionary<string, Integer>;
  GLatinByUnicode: TDictionary<string, Integer>;
  GUnicode: TDictionary<string, string>;

function StdFontFromParts(const AFamily: string; ABold, AItalic: Boolean): Integer;
var
  F: string;
begin
  F := LowerCase(AFamily);
  if (F = 'helvetica') or (F = 'arial') or (F = 'arialmt') then
    Result := STD_HELVETICA
  else if (F = 'times') or (F = 'timesroman') or (F = 'timesnewroman') or
          (F = 'timesnewromanps') or (F = 'timesnewromanpsmt') then
    Result := STD_TIMES
  else if (F = 'courier') or (F = 'couriernew') or (F = 'couriernewps') or
          (F = 'couriernewpsmt') then
    Result := STD_COURIER
  else if F = 'symbol' then
    Exit(STD_SYMBOL)
  else if (F = 'zapfdingbats') or (F = 'dingbats') then
    Exit(STD_DINGBATS)
  else
    Exit(-1);
  if ABold then Inc(Result);
  if AItalic then Inc(Result, 2);
end;

function StripSubset(const AName: string): string;
begin
  Result := AName.Replace(' ', '');
  if (Length(Result) > 7) and (Result[7] = '+') then
    Delete(Result, 1, 7);
end;

function StdFontIndex(const ABaseFont: string): Integer;
var
  Name, Style: string;
  P: Integer;
begin
  Name := StripSubset(ABaseFont);
  P := Name.IndexOfAny([',', '-']);
  if P >= 0 then
  begin
    Style := LowerCase(Name.Substring(P + 1));
    Name  := Name.Substring(0, P);
  end else
    Style := '';
  Result := StdFontFromParts(Name, Style.Contains('bold'),
    Style.Contains('italic') or Style.Contains('oblique'));
end;

function StdFontSubstitute(AFlags: Integer; const ABaseFont: string): Integer;
const
  FIXED_PITCH = 1;
  SERIF       = 2;
  ITALIC      = 64;
  FORCE_BOLD  = 1 shl 18;
var
  L: string;
begin
  Result := StdFontIndex(ABaseFont);
  if Result >= 0 then Exit;
  L := LowerCase(StripSubset(ABaseFont));
  if AFlags and FIXED_PITCH <> 0 then
    Result := STD_COURIER
  else if AFlags and SERIF <> 0 then
    Result := STD_TIMES
  else
    Result := STD_HELVETICA;
  if (AFlags and FORCE_BOLD <> 0) or L.Contains('bold') or L.Contains('black') or
     L.Contains('heavy') then
    Inc(Result);
  if (AFlags and ITALIC <> 0) or L.Contains('italic') or L.Contains('oblique') then
    Inc(Result, 2);
end;

function StdFontEncoding(AFont: Integer): TPDFStdEncoding;
begin
  case AFont of
    STD_SYMBOL:   Result := TPDFStdEncoding.Symbol;
    STD_DINGBATS: Result := TPDFStdEncoding.ZapfDingbats;
  else
    Result := TPDFStdEncoding.Standard;
  end;
end;

function StdEncodingGlyph(AEncoding: TPDFStdEncoding; ACode: Integer): string;
begin
  if (ACode < 0) or (ACode > 255) then Exit('');
  case AEncoding of
    TPDFStdEncoding.Standard:     Result := ENC_STANDARD[ACode];
    TPDFStdEncoding.WinAnsi:      Result := ENC_WINANSI[ACode];
    TPDFStdEncoding.MacRoman:     Result := ENC_MACROMAN[ACode];
    TPDFStdEncoding.Symbol:       Result := ENC_SYMBOL[ACode];
    TPDFStdEncoding.ZapfDingbats: Result := ENC_DINGBATS[ACode];
  else
    Result := '';
  end;
end;

function StdGlyphWidth(AFont: Integer; const AGlyph: string; out AWidth: Integer): Boolean;
var
  I: Integer;
begin
  AWidth := 0;
  case AFont of
    0..11:
    begin
      // A name outside the Latin set (uni00E9, Ntilde.sc...) by its Unicode
      Result := GLatin.TryGetValue(AGlyph, I) or
        GLatinByUnicode.TryGetValue(GlyphNameToUnicode(AGlyph), I);
      if Result then AWidth := LATIN_WIDTHS[AFont, I];
    end;
    STD_SYMBOL:
    begin
      Result := GSymbol.TryGetValue(AGlyph, I);
      if Result then AWidth := SYMBOL_WIDTHS[I];
    end;
    STD_DINGBATS:
    begin
      Result := GDingbats.TryGetValue(AGlyph, I);
      if Result then AWidth := DINGBATS_WIDTHS[I];
    end;
  else
    Result := False;
  end;
end;

function GlyphNameToUnicode(const AGlyph: string): string;
var
  Base: string;
  V, P: Integer;
begin
  if AGlyph = '' then Exit('');
  if GUnicode.TryGetValue(AGlyph, Result) then Exit;
  // Variants such as "a.sc" or "f_i" (only the first component is mapped)
  Base := AGlyph;
  P := Base.IndexOf('.');
  if P > 0 then
  begin
    Base := Base.Substring(0, P);
    if GUnicode.TryGetValue(Base, Result) then Exit;
  end;
  if Base.StartsWith('uni') and (Length(Base) >= 7) and
     TryStrToInt('$' + Base.Substring(3, 4), V) then
    Exit(Char(V));
  if Base.StartsWith('u') and (Length(Base) in [5..7]) and
     TryStrToInt('$' + Base.Substring(1), V) and (V >= $20) and (V <= $10FFFF) then
    Exit(Char.ConvertFromUtf32(V));
  Result := '';
end;

procedure BuildIndexes;
begin
  GLatin := TDictionary<string, Integer>.Create(Length(LATIN_GLYPHS));
  for var I := 0 to High(LATIN_GLYPHS) do GLatin.Add(LATIN_GLYPHS[I], I);
  GSymbol := TDictionary<string, Integer>.Create(Length(SYMBOL_GLYPHS));
  for var I := 0 to High(SYMBOL_GLYPHS) do GSymbol.Add(SYMBOL_GLYPHS[I], I);
  GDingbats := TDictionary<string, Integer>.Create(Length(DINGBATS_GLYPHS));
  for var I := 0 to High(DINGBATS_GLYPHS) do GDingbats.Add(DINGBATS_GLYPHS[I], I);
  GUnicode := TDictionary<string, string>.Create(Length(AGL));
  for var I := 0 to High(AGL) do GUnicode.Add(AGL[I].N, AGL[I].U);
  GLatinByUnicode := TDictionary<string, Integer>.Create(Length(LATIN_GLYPHS));
  for var I := 0 to High(LATIN_GLYPHS) do
    GLatinByUnicode.TryAdd(GlyphNameToUnicode(LATIN_GLYPHS[I]), I);
end;

initialization
  BuildIndexes;

finalization
  GLatinByUnicode.Free;
  GUnicode.Free;
  GDingbats.Free;
  GSymbol.Free;
  GLatin.Free;

end.
''')
