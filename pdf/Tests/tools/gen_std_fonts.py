"""Generates pdf/Src/Core/uPDF.StdFonts.pas: the metrics of the 14 standard
PDF fonts, the simple-font encodings of ISO 32000-1 Annex D and the Adobe
Glyph List (glyph name -> Unicode).

Inputs:
  - the 14 Core AFM files from Adobe (Courier*.afm, Helvetica*.afm,
    Times*.afm, Symbol.afm, ZapfDingbats.afm); they are also shipped by
    matplotlib in mpl-data/fonts/pdfcorefonts
  - glyphlist.txt and zapfdingbats.txt from
    https://github.com/adobe-type-tools/agl-aglfn

StandardEncoding and the built-in encodings of Symbol and ZapfDingbats are
the C codes of the AFM files; WinAnsiEncoding and MacRomanEncoding are
derived from cp1252 / mac_roman with the deviations listed in Annex D.

Usage: python gen_std_fonts.py <afm dir> <agl dir> > uPDF.StdFonts.pas
"""
import os, sys

afmdir, agldir = sys.argv[1], sys.argv[2]
FONTS = ['Courier', 'Courier-Bold', 'Courier-Oblique', 'Courier-BoldOblique',
         'Helvetica', 'Helvetica-Bold', 'Helvetica-Oblique', 'Helvetica-BoldOblique',
         'Times-Roman', 'Times-Bold', 'Times-Italic', 'Times-BoldItalic',
         'Symbol', 'ZapfDingbats']


def read_afm(name):
    widths, codes = {}, {}
    for line in open(os.path.join(afmdir, name + '.afm'), encoding='latin-1'):
        if not line.startswith('C '):
            continue
        f = dict(p.strip().split(' ', 1) for p in line.split(';') if p.strip())
        code, glyph, wx = int(f['C']), f['N'], int(f['WX'])
        widths[glyph] = wx
        if code >= 0:
            codes[code] = glyph
    return widths, codes


afm = {n: read_afm(n) for n in FONTS}


def read_agl(fname):
    res = {}
    for line in open(os.path.join(agldir, fname), encoding='utf-8'):
        if line.startswith('#') or not line.strip():
            continue
        name, cps = line.strip().split(';')
        res[name] = ''.join(chr(int(c, 16)) for c in cps.split())
    return res


agl = read_agl('glyphlist.txt')
zapf = read_agl('zapfdingbats.txt')

# Latin fonts share one glyph set
latin = sorted(afm['Courier'][0])
for n in FONTS[:12]:
    assert sorted(afm[n][0]) == latin, n
symbol = sorted(afm['Symbol'][0])
dingbats = sorted(afm['ZapfDingbats'][0])

# unicode -> preferred glyph name (a Latin AFM name first)
rev = {}
for name, u in agl.items():
    if len(u) != 1:
        continue
    if u not in rev or (name in latin and rev[u] not in latin):
        rev[u] = name


def from_codec(codec, fixes):
    enc = [''] * 256
    for c in range(32, 256):
        try:
            u = bytes([c]).decode(codec)
        except UnicodeDecodeError:
            continue
        enc[c] = rev.get(u, '')
    for c, name in fixes.items():
        enc[c] = name
    return enc


standard = [''] * 256
for c, g in afm['Helvetica'][1].items():
    standard[c] = g
# Annex D, note 3: unused codes above 040 map to bullet; 0240 is space and 0255 hyphen
win = from_codec('cp1252', {0x7F: 'bullet', 0x81: 'bullet', 0x8D: 'bullet', 0x8F: 'bullet',
                            0x90: 'bullet', 0x9D: 'bullet', 0xA0: 'space', 0xAD: 'hyphen'})
# Annex D: 0312 is space, 0333 currency (the codec has the euro), 0360 is undefined
mac = from_codec('mac_roman', {0x7F: '', 0xCA: 'space', 0xDB: 'currency', 0xF0: ''})
# the math characters of the Mac character set are not in the Latin text fonts
# and not in the MacRomanEncoding of Annex D
mac = [g if g in latin else '' for g in mac]
sym = [''] * 256
for c, g in afm['Symbol'][1].items():
    sym[c] = g
zd = [''] * 256
for c, g in afm['ZapfDingbats'][1].items():
    zd[c] = g
for enc in (standard, win, mac):
    for g in enc:
        assert g == '' or g in latin, g

uni = dict(agl)
for name, u in zapf.items():
    assert name not in uni
    uni[name] = u
for g in latin + symbol:
    assert g in uni, g


def pstr(s):
    return "'" + s.replace("'", "''") + "'"


def pchars(u):
    return ''.join('#$%04X' % ord(ch) for ch in u)


def rows(items, per, indent='    '):
    out, line = [], []
    for k, it in enumerate(items):
        line.append(it)
        if len(line) == per:
            out.append(indent + ', '.join(line) + (',' if k < len(items) - 1 else ''))
            line = []
    if line:
        out.append(indent + ', '.join(line))
    return out


notice = open(os.path.join(afmdir, 'readme.txt'), encoding='latin-1').read()
para = notice[notice.index('This file and the 14'):].strip()
agl_lic = [l[2:] if l.startswith('# ') else l[1:] for l in
           open(os.path.join(agldir, 'glyphlist.txt'), encoding='utf-8').read().split('\n')[1:33]]

w = sys.stdout.write
